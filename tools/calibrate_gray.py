#!/usr/bin/env python3
"""Fit per-channel software thresholds from stationary, labeled captures.
This writes MCU-side configuration only; it never writes sensor EEPROM.
"""
import argparse
import csv
import hashlib
import json
from pathlib import Path
import statistics
import struct


def capture(prefix):
    diagnostic = Path(str(prefix) + '-diag.bin').read_bytes()
    samples_path = Path(str(prefix) + '-samples.bin')
    data = samples_path.read_bytes()
    if len(diagnostic) != 156 or len(data) != 2560:
        raise ValueError('Wrong capture layout')
    d = struct.unpack_from('<15I', diagnostic)
    if d[0] != 0x474C524E or d[9] != 128 or any(d[5:9]):
        raise ValueError('Incomplete capture or communication error')
    rows = list(struct.iter_unpack('<I8H', data))
    gaps = [(b[0]-a[0]) & 0xFFFFFFFF for a, b in zip(rows, rows[1:])]
    if any(not 0 < gap <= 200 for gap in gaps):
        raise ValueError('Capture contains a timing discontinuity')
    return rows, dict(generation=d[13], source=str(samples_path),
                     sha256=hashlib.sha256(data).hexdigest(),
                     old_threshold=list(struct.unpack_from('<8H', diagnostic, 76)))


def fit(white, black):
    channels = []
    for i in range(1, 9):
        w, b = [r[i] for r in white], [r[i] for r in black]
        high = statistics.mean(b) > statistics.mean(w)
        low_edge, high_edge = (max(w), min(b)) if high else (max(b), min(w))
        gap = high_edge-low_edge
        noise = max(max(w)-min(w), max(b)-min(b))
        # Conservative initial quality gates in raw ADC units, not a datasheet limit.
        if gap < 128 or gap < 8*max(1, noise):
            raise ValueError(f'Channel {i}: black/white separation inadequate ({gap=}, {noise=})')
        channels.append(dict(channel=i,white_min=min(w),white_max=max(w),
            white_mean=statistics.mean(w),black_min=min(b),black_max=max(b),
            black_mean=statistics.mean(b),gap=gap,black_high=high,
            threshold=(low_edge+high_edge)//2,hysteresis=max(16,gap//10)))
    return channels


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--white',required=True,type=Path,help='Capture path prefix')
    p.add_argument('--black',required=True,type=Path,help='Capture path prefix')
    p.add_argument('--output',required=True,type=Path,help='JSON report path')
    p.add_argument('--header',required=True,type=Path)
    a=p.parse_args()
    white,wm=capture(a.white);black,bm=capture(a.black)
    if wm['generation']==bm['generation'] or wm['sha256']==bm['sha256']:
        raise ValueError('White and black must be distinct captures')
    channels=fit(white,black)
    high=sum((1<<i) for i,c in enumerate(channels) if c['black_high'])
    result=dict(white_capture=wm,black_capture=bm,channels=channels,
        black_high_mask=high,independent_validation_complete=False,
        note='Stationary training samples; require independent white/black and dynamic track validation.')
    a.output.parent.mkdir(parents=True,exist_ok=True)
    a.output.write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n')
    with a.output.with_suffix('.csv').open('w',newline='') as f:
        w=csv.writer(f);w.writerow(['surface','tick_ms',*[f'ch{i}' for i in range(1,9)]])
        for label,rows in [('white',white),('black',black)]:
            for row in rows:w.writerow([label,*row])
    thresholds=','.join(str(c['threshold']) for c in channels)
    hysteresis=','.join(str(c['hysteresis']) for c in channels)
    a.header.write_text('#ifndef GRAY_CALIBRATION_H\n#define GRAY_CALIBRATION_H\n'
        '#include <stdint.h>\n/* Generated by tools/calibrate_gray.py; raw channel order S1..S8.\n'
        ' * 128 white + 128 black samples, 2026-10-23; independent checks pending. */\n'
        '#define GRAY_CALIBRATION_VALID_MASK 0xFFU\n'
        f'#define GRAY_CALIBRATION_BLACK_HIGH_MASK 0x{high:02X}U\n'
        f'static const uint16_t gray_calibration_threshold[8]={{{thresholds}}};\n'
        f'static const uint16_t gray_calibration_hysteresis[8]={{{hysteresis}}};\n#endif\n')
    print(json.dumps(result,ensure_ascii=False,indent=2))


if __name__=='__main__':
    main()
